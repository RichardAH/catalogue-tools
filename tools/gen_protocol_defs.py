#!/usr/bin/env python3
"""Regenerate src/protocol_defs.inc from a xahaud checkout.

    tools/gen_protocol_defs.py /path/to/xahaud > src/protocol_defs.inc

Reads the X-macro definition files xahaud itself compiles from, so the field,
transaction-type, ledger-entry-type, TER and amendment tables in catl always
match the node they were generated against.
"""
import re, sys, os

STI = dict(UINT16=1, UINT32=2, UINT64=3, UINT128=4, UINT256=5, AMOUNT=6, VL=7,
           ACCOUNT=8, NUMBER=9, OBJECT=14, ARRAY=15, UINT8=16, UINT160=17,
           PATHSET=18, VECTOR256=19, UINT96=20, UINT192=21, UINT384=22,
           UINT512=23, ISSUE=24, XCHAIN_BRIDGE=25, CURRENCY=26)

def main(root):
    d = os.path.join(root, 'include/xrpl/protocol/detail')
    out = ['// GENERATED by tools/gen_protocol_defs.py -- do not edit by hand.',
           '// Source: xahaud include/xrpl/protocol/detail/*.macro, TER.h', '']

    out.append('// CATL_FIELD(name, sti, code, baseTen)')
    for m in re.finditer(r'^(?:UN)?TYPED_SFIELD\(\s*sf(\w+)\s*,\s*(\w+)\s*,\s*(\d+)([^)]*)\)',
                         open(os.path.join(d, 'sfields.macro')).read(), re.M):
        name, typ, code, rest = m.groups()
        if typ not in STI:
            continue
        out.append('CATL_FIELD(%s, %d, %s, %d)' % (name, STI[typ], code,
                   1 if 'sMD_BaseTen' in rest else 0))

    out.append('\n// CATL_TXTYPE(name, code)')
    for m in re.finditer(r'^TRANSACTION\(\s*tt\w+\s*,\s*(\d+)\s*,\s*(\w+)',
                         open(os.path.join(d, 'transactions.macro')).read(), re.M):
        out.append('CATL_TXTYPE(%s, %s)' % (m.group(2), m.group(1)))

    out.append('\n// CATL_LETYPE(name, code)')
    for m in re.finditer(r"^LEDGER_ENTRY(?:_DUPLICATE)?\(\s*lt\w+\s*,\s*([^,]+?)\s*,\s*(\w+)",
                         open(os.path.join(d, 'ledger_entries.macro')).read(), re.M):
        code, name = m.groups()
        code = str(ord(code[1])) if code.startswith("'") else str(int(code, 0))
        out.append('CATL_LETYPE(%s, %s)' % (name, code))

    out.append('\n// CATL_TER(name, code)  (tes/tec only: the codes stored in metadata)')
    ter = open(os.path.join(root, 'include/xrpl/protocol/TER.h')).read()
    for m in re.finditer(r'^\s*(tes\w+|tec\w+)\s*=\s*(\d+)', ter, re.M):
        out.append('CATL_TER(%s, %s)' % m.groups())

    out.append('\n// CATL_AMENDMENT("name")  (ID = SHA512Half(name))')
    for m in re.finditer(r'^XRPL_(FEATURE|FIX|RETIRE)\s*\(\s*(\w+)',
                         open(os.path.join(d, 'features.macro')).read(), re.M):
        kind, name = m.groups()
        out.append('CATL_AMENDMENT("%s")' % (('fix' + name) if kind == 'FIX' else name))
    print('\n'.join(out))

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '.')
